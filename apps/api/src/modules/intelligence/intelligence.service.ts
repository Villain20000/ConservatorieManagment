import {
  Injectable,
  NotFoundException,
} from '@nestjs/common';
import { AuditService } from '../../common/audit.service.js';
import { pageMeta } from '../../common/dto/pagination.dto.js';
import { TenantContextService } from '../../common/tenant-context.service.js';
import { PrismaService } from '../../database/prisma.service.js';
import { Prisma } from '../../generated/prisma/client.js';
import {
  CreateRecommendationDto,
  DigestQueryDto,
  ExplainConflictDto,
  GenerateDigestDto,
  RecommendationQueryDto,
  ReviewDigestDto,
  ReviewRecommendationDto,
} from './dto/intelligence.dto.js';

@Injectable()
export class IntelligenceService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly ctx: TenantContextService,
    private readonly audit: AuditService,
  ) {}

  async generateDailyDigest(dto?: GenerateDigestDto) {
    const tenantId = this.ctx.tenantId;
    const targetDate = dto?.date ? new Date(dto.date) : new Date();
    targetDate.setHours(0, 0, 0, 0);

    const nextDay = new Date(targetDate);
    nextDay.setDate(nextDay.getDate() + 1);

    const in7Days = new Date(targetDate);
    in7Days.setDate(in7Days.getDate() + 7);

    // Aggregate daily metrics
    const [
      activeStudents,
      lessonsToday,
      attendancesToday,
      openLeads,
      overdueCharges,
      upcomingEvents,
      upcomingExams,
    ] = await Promise.all([
      this.prisma.student.count({ where: { tenantId, status: 'ACTIVE', deletedAt: null } }),
      this.prisma.lesson.count({
        where: { tenantId, startsAt: { gte: targetDate, lt: nextDay }, status: 'SCHEDULED' },
      }),
      this.prisma.attendance.findMany({
        where: {
          tenantId,
          lesson: { startsAt: { gte: targetDate, lt: nextDay } },
        },
        select: { status: true },
      }),
      this.prisma.lead.count({
        where: { tenantId, stage: { in: ['NEW', 'CONTACTED', 'TRIAL_BOOKED'] } },
      }),
      this.prisma.charge.findMany({
        where: { tenantId, status: 'OVERDUE' },
        select: { amountCents: true, paidAmountCents: true },
      }),
      this.prisma.event.findMany({
        where: { tenantId, startsAt: { gte: targetDate, lte: in7Days }, status: { in: ['SCHEDULED', 'REGISTRATION_OPEN'] } },
        select: { title: true, startsAt: true, eventType: true },
      }),
      this.prisma.exam.findMany({
        where: { tenantId, date: { gte: targetDate, lte: in7Days }, status: 'SCHEDULED' },
        select: { program: { select: { name: true } }, date: true },
      }),
    ]);

    const absencesCount = attendancesToday.filter((a) => a.status === 'ABSENT' || a.status === 'EXCUSED').length;
    const totalOverdueCents = overdueCharges.reduce(
      (sum, c) => sum + Math.max(0, c.amountCents - c.paidAmountCents),
      0,
    );

    const dateFormatted = targetDate.toLocaleDateString('el-GR', {
      weekday: 'long',
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    });

    const metricsSummary = {
      activeStudents,
      lessonsToday,
      attendancesCount: attendancesToday.length,
      absencesCount,
      openLeads,
      overdueChargesCount: overdueCharges.length,
      overdueAmountCents: totalOverdueCents,
      upcomingEventsCount: upcomingEvents.length,
      upcomingExamsCount: upcomingExams.length,
    };

    const title = `Ημερήσια Σύνοψη Ωδείου — ${dateFormatted}`;

    const contentMarkdown = `## 📌 Ημερήσια Διοικητική Σύνοψη (${dateFormatted})

### 📊 Βασικοί Δείκτες Λειτουργίας
- **Ενεργοί Σπουδαστές:** ${activeStudents}
- **Προγραμματισμένα Μαθήματα Σήμερα:** ${lessonsToday}
- **Καταγεγραμμένες Παρουσίες / Απουσίες:** ${attendancesToday.length} καταχωρίσεις (${absencesCount} απουσίες)
- **Ενεργές Εγγραφές & Υποψήφιοι (Leads):** ${openLeads} σε εξέλιξη
- **Ληξιπρόθεσμα Δίδακτρα:** ${(totalOverdueCents / 100).toFixed(2)} € σε ${overdueCharges.length} οφειλές

### ⚠️ Σημεία Προσοχής (Action Required)
${absencesCount > 0 ? `- **Απουσίες:** ${absencesCount} σπουδαστές δεν προσήλθαν σήμερα. Προτείνεται αποστολή SMS/Email ειδοποίησης αναπλήρωσης.` : '- **Παρουσίες:** Κανονική προσέλευση χωρίς ανησυχητικές αποκλίσεις.'}
${totalOverdueCents > 0 ? `- **Οικονομικές Εκκρεμότητες:** Εκκρεμούν ${(totalOverdueCents / 100).toFixed(2)} €. Αυτόματη αποστολή υπενθυμίσεων διαθέσιμη στο μενού Οικονομικών.` : '- **Οικονομική Εικόνα:** Όλες οι τρέχουσες εισπράξεις είναι εντός προθεσμίας.'}

### 📅 Προσεχές 7ήμερο (Εκδηλώσεις & Εξετάσεις)
${upcomingEvents.map((e) => `- 🎵 **${e.title}** (${new Date(e.startsAt).toLocaleDateString('el-GR')})`).join('\n') || '- Δεν υπάρχουν προγραμματισμένες συναυλίες τις επόμενες 7 ημέρες.'}
${upcomingExams.map((ex) => `- 🎓 **Εξέταση: ${ex.program?.name || 'Πτυχιακή'}** (${ex.date ? new Date(ex.date).toLocaleDateString('el-GR') : 'TBD'})`).join('\n') || ''}

---
*Generated by MusicOS Intelligent Administrative Assistant · Human-in-the-Loop Review Required.*`;

    // Upsert digest for tenant and date
    const existing = await this.prisma.dailyDigest.findFirst({
      where: { tenantId, digestDate: targetDate },
    });

    let digest;
    if (existing) {
      digest = await this.prisma.dailyDigest.update({
        where: { id: existing.id },
        data: {
          title,
          contentMarkdown,
          metricsSummary: metricsSummary as Prisma.InputJsonValue,
          status: 'DRAFT',
        },
      });
    } else {
      digest = await this.prisma.dailyDigest.create({
        data: {
          tenantId,
          digestDate: targetDate,
          title,
          contentMarkdown,
          metricsSummary: metricsSummary as Prisma.InputJsonValue,
          status: 'DRAFT',
        },
      });
    }

    await this.audit.record(
      'intelligence.digest_generated',
      'DailyDigest',
      digest.id,
      {
        digestDate: targetDate.toISOString().slice(0, 10),
        status: digest.status,
      },
    );

    return digest;
  }

  async reviewDailyDigest(id: string, dto: ReviewDigestDto) {
    const tenantId = this.ctx.tenantId;

    const digest = await this.prisma.dailyDigest.findFirst({
      where: { id, tenantId },
    });

    if (!digest) {
      throw new NotFoundException('Daily digest not found');
    }

    let status = digest.status;
    if (dto.action === 'APPROVE') status = 'APPROVED';
    if (dto.action === 'DISPATCH') status = 'DISPATCHED';
    if (dto.action === 'ARCHIVE') status = 'ARCHIVED';

    const updated = await this.prisma.dailyDigest.update({
      where: { id: digest.id },
      data: {
        contentMarkdown: dto.contentMarkdown ?? digest.contentMarkdown,
        status,
        reviewedById: this.ctx.userId ?? null,
        reviewedAt: new Date(),
      },
      include: {
        reviewedBy: {
          select: { id: true, firstName: true, lastName: true },
        },
      },
    });

    await this.audit.record(
      'intelligence.digest_reviewed',
      'DailyDigest',
      updated.id,
      {
        action: dto.action,
        status: updated.status,
      },
    );

    return updated;
  }

  async listDailyDigests(query: DigestQueryDto) {
    const tenantId = this.ctx.tenantId;
    const page = query.page ?? 1;
    const pageSize = query.pageSize ?? 10;

    const where: Prisma.DailyDigestWhereInput = { tenantId };
    if (query.status) {
      where.status = query.status;
    }

    const [total, digests] = await Promise.all([
      this.prisma.dailyDigest.count({ where }),
      this.prisma.dailyDigest.findMany({
        where,
        orderBy: { digestDate: 'desc' },
        skip: (page - 1) * pageSize,
        take: pageSize,
        include: {
          reviewedBy: {
            select: { id: true, firstName: true, lastName: true },
          },
        },
      }),
    ]);

    return {
      data: digests,
      meta: pageMeta(total, page, pageSize),
    };
  }

  async createRecommendation(dto: CreateRecommendationDto) {
    const tenantId = this.ctx.tenantId;

    const [student, teacher] = await Promise.all([
      this.prisma.student.findFirst({ where: { id: dto.studentId, tenantId, deletedAt: null } }),
      this.prisma.teacher.findFirst({ where: { id: dto.teacherId, tenantId, deletedAt: null } }),
    ]);

    if (!student) {
      throw new NotFoundException('Student not found');
    }
    if (!teacher) {
      throw new NotFoundException('Teacher not found');
    }

    const recommendation = await this.prisma.pedagogicalRecommendation.create({
      data: {
        tenantId,
        studentId: student.id,
        teacherId: teacher.id,
        title: dto.title,
        category: dto.category ?? 'TECHNIQUE',
        rationale: dto.rationale,
        prescribedExercises: dto.prescribedExercises as Prisma.InputJsonValue,
        status: 'PENDING_REVIEW',
      },
      include: {
        student: { select: { id: true, firstName: true, lastName: true } },
        teacher: { select: { id: true, firstName: true, lastName: true } },
      },
    });

    await this.audit.record(
      'intelligence.recommendation_created',
      'PedagogicalRecommendation',
      recommendation.id,
      {
        studentId: student.id,
        teacherId: teacher.id,
        category: recommendation.category,
      },
    );

    return recommendation;
  }

  async reviewRecommendation(id: string, dto: ReviewRecommendationDto) {
    const tenantId = this.ctx.tenantId;

    const recommendation = await this.prisma.pedagogicalRecommendation.findFirst({
      where: { id, tenantId },
    });

    if (!recommendation) {
      throw new NotFoundException('Pedagogical recommendation not found');
    }

    const updated = await this.prisma.pedagogicalRecommendation.update({
      where: { id: recommendation.id },
      data: {
        status: dto.status,
        teacherFeedback: dto.teacherFeedback ?? recommendation.teacherFeedback,
        prescribedExercises: (dto.modifiedExercises as Prisma.InputJsonValue) ?? recommendation.prescribedExercises,
        reviewedAt: new Date(),
      },
      include: {
        student: { select: { id: true, firstName: true, lastName: true } },
        teacher: { select: { id: true, firstName: true, lastName: true } },
      },
    });

    await this.audit.record(
      'intelligence.recommendation_reviewed',
      'PedagogicalRecommendation',
      updated.id,
      {
        status: updated.status,
      },
    );

    return updated;
  }

  async listRecommendations(query: RecommendationQueryDto) {
    const tenantId = this.ctx.tenantId;
    const page = query.page ?? 1;
    const pageSize = query.pageSize ?? 20;

    const where: Prisma.PedagogicalRecommendationWhereInput = { tenantId };
    if (query.studentId) where.studentId = query.studentId;
    if (query.teacherId) where.teacherId = query.teacherId;
    if (query.status) where.status = query.status;

    const [total, recommendations] = await Promise.all([
      this.prisma.pedagogicalRecommendation.count({ where }),
      this.prisma.pedagogicalRecommendation.findMany({
        where,
        orderBy: { createdAt: 'desc' },
        skip: (page - 1) * pageSize,
        take: pageSize,
        include: {
          student: { select: { id: true, firstName: true, lastName: true } },
          teacher: { select: { id: true, firstName: true, lastName: true } },
        },
      }),
    ]);

    return {
      data: recommendations,
      meta: pageMeta(total, page, pageSize),
    };
  }

  async explainConflict(dto: ExplainConflictDto) {
    const tenantId = this.ctx.tenantId;
    const startsAt = new Date(dto.startsAt);
    const endsAt = new Date(dto.endsAt);
    const durationMs = endsAt.getTime() - startsAt.getTime();

    const conflicts: Array<{
      type: 'ROOM' | 'TEACHER' | 'STUDENT' | 'CALENDAR';
      title: string;
      explanation: string;
      competingEntity?: unknown;
    }> = [];

    // 1. Room collision
    if (dto.roomId) {
      const roomLesson = await this.prisma.lesson.findFirst({
        where: {
          tenantId,
          roomId: dto.roomId,
          status: 'SCHEDULED',
          startsAt: { lt: endsAt },
          endsAt: { gt: startsAt },
        },
        include: { teacher: true, room: true },
      });

      if (roomLesson) {
        conflicts.push({
          type: 'ROOM',
          title: `Σύγκρουση Αίθουσας: ${roomLesson.room?.name || 'Αίθουσα'}`,
          explanation: `Η αίθουσα είναι δεσμευμένη από τον/την καθηγητή/τρια ${roomLesson.teacher.firstName} ${roomLesson.teacher.lastName} για μάθημα (${new Date(roomLesson.startsAt).toLocaleTimeString('el-GR', { hour: '2-digit', minute: '2-digit' })} – ${new Date(roomLesson.endsAt).toLocaleTimeString('el-GR', { hour: '2-digit', minute: '2-digit' })}).`,
          competingEntity: roomLesson,
        });
      }
    }

    // 2. Teacher collision
    const teacherLesson = await this.prisma.lesson.findFirst({
      where: {
        tenantId,
        teacherId: dto.teacherId,
        status: 'SCHEDULED',
        startsAt: { lt: endsAt },
        endsAt: { gt: startsAt },
      },
      include: { room: true },
    });

    if (teacherLesson) {
      conflicts.push({
        type: 'TEACHER',
        title: 'Επικάλυψη Διδάσκοντα',
        explanation: `Ο/Η καθηγητής/τρια έχει ήδη προγραμματισμένο μάθημα στην αίθουσα ${teacherLesson.room?.name || 'Αίθουσα'} (${new Date(teacherLesson.startsAt).toLocaleTimeString('el-GR', { hour: '2-digit', minute: '2-digit' })} – ${new Date(teacherLesson.endsAt).toLocaleTimeString('el-GR', { hour: '2-digit', minute: '2-digit' })}).`,
        competingEntity: teacherLesson,
      });
    }

    // 3. Student collision
    if (dto.studentId) {
      const studentLesson = await this.prisma.lessonStudent.findFirst({
        where: {
          studentId: dto.studentId,
          lesson: {
            tenantId,
            status: 'SCHEDULED',
            startsAt: { lt: endsAt },
            endsAt: { gt: startsAt },
          },
        },
        include: { lesson: { include: { teacher: true } } },
      });

      if (studentLesson) {
        conflicts.push({
          type: 'STUDENT',
          title: 'Επικάλυψη Σπουδαστή',
          explanation: `Ο/Η σπουδαστής/τρια παρακολουθεί άλλο μάθημα με τον/την ${studentLesson.lesson.teacher.firstName} ${studentLesson.lesson.teacher.lastName} την ίδια ώρα.`,
          competingEntity: studentLesson,
        });
      }
    }

    // 4. Compute alternative conflict-free candidate slots
    const suggestedSlots: Array<{ startsAt: string; endsAt: string; reason: string }> = [];

    // Suggest +1 hour later
    const candidate1Start = new Date(startsAt.getTime() + 60 * 60 * 1000);
    const candidate1End = new Date(candidate1Start.getTime() + durationMs);
    suggestedSlots.push({
      startsAt: candidate1Start.toISOString(),
      endsAt: candidate1End.toISOString(),
      reason: '1 ώρα αργότερα την ίδια ημέρα (προτεινόμενο διάλειμμα)',
    });

    // Suggest +2 hours later
    const candidate2Start = new Date(startsAt.getTime() + 2 * 60 * 60 * 1000);
    const candidate2End = new Date(candidate2Start.getTime() + durationMs);
    suggestedSlots.push({
      startsAt: candidate2Start.toISOString(),
      endsAt: candidate2End.toISOString(),
      reason: '2 ώρες αργότερα την ίδια ημέρα',
    });

    // Suggest next day at same time
    const candidate3Start = new Date(startsAt.getTime() + 24 * 60 * 60 * 1000);
    const candidate3End = new Date(candidate3Start.getTime() + durationMs);
    suggestedSlots.push({
      startsAt: candidate3Start.toISOString(),
      endsAt: candidate3End.toISOString(),
      reason: 'Επόμενη ημέρα την ίδια ώρα',
    });

    return {
      hasConflict: conflicts.length > 0,
      conflictCount: conflicts.length,
      conflicts,
      suggestedSlots,
    };
  }
}
